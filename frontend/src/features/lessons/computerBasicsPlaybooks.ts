const TITLE_IDS: Record<string, string> = {
  'Файл и папка': 'file-folder',
  'Расширение файла': 'extension',
  'Где хранить': 'where',
}

export function computerBasicsPackId(keys: string[], seedTitle: string): string | null {
  const raw = keys[0]
  if (typeof raw === 'string' && raw.startsWith('desktop:')) return raw
  return TITLE_IDS[seedTitle] ?? null
}

export function getComputerBasicsPack(
  locale: 'ru' | 'tg',
  keys: string[],
  seedTitle: string,
): TeachPack | null {
  const id = computerBasicsPackId(keys, seedTitle)
  if (!id) return null
  const catalog = locale === 'tg' ? TG : RU
  return catalog[id] ?? RU[id] ?? null
}
