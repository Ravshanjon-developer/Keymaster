/** Chord id: sorted lowercase keys joined with `+`, e.g. `control+x`. */
export function chordExplainId(keys: string[]): string {
  return normalizeShortcutKeys(keys)
    .map((k) => k.toLowerCase())
    .sort()
    .join('+')
}

