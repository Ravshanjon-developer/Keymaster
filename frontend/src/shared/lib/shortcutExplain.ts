function pickLocale(entry: Bilingual, locale: Locale): string {
  return locale === 'tg' ? entry.tg : entry.ru
}

/** Detailed plain explanation for the back of a training/review card. */
export function explainShortcut(
  keys: string[],
  locale: Locale,
  opts?: { title?: string | null; description?: string | null },
): string {
  const id = chordExplainId(keys)
  const known = EXPLAIN[id]
  if (known) return pickLocale(known, locale)

  const title = (opts?.title ?? '').trim()
  const description = (opts?.description ?? '').trim()
  const lead = description.length > title.length + 8 ? description : title || description

  if (lead && lead.length >= 24) {
    // Seed already has a real sentence — use it as the explanation body.
    return lead
  }

  if (lead) {
    return locale === 'tg'
      ? `${lead}. ${FALLBACK.tg}`
      : `${lead}. ${FALLBACK.ru}`
  }

  return pickLocale(FALLBACK, locale)
}

/** Prefer a long seed note; otherwise use the chord library / fallback. */
export function resolveShortcutDetail(
  keys: string[],
  locale: Locale,
  seedDetail: string,
  opts?: { title?: string | null; description?: string | null },
): string {
  const seeded = seedDetail.trim()
  if (seeded.length >= 48) return seeded
  return explainShortcut(keys, locale, opts)
}
