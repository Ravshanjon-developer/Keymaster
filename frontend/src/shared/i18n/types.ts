type NestedKeyOf<T> = {
  [G in keyof T & string]: {
    [K in keyof T[G] & string]: `${G}.${K}`
  }[keyof T[G] & string]
}[keyof T & string]

export type TranslationKey = NestedKeyOf<Messages>

export type TranslateParams = Record<string, string | number>

export type TranslateFn = (key: TranslationKey, params?: TranslateParams) => string
